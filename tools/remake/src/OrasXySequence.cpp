Bytes XySequenceToOras(const Bytes& x, const Bytes& xSizes, const Bytes& orasSizes, const std::function<void(uint16_t, Bytes&)>& record)
{
    if (x.size() < 0x14 || std::string(x.begin(), x.begin() + 4) != "SESD" || U32(x, 4) != 2) throw FormatError("X/Y sequence: not an SESD file of version 2");
    if (xSizes.size() != 4 * 186 || orasSizes.size() != 4 * 213) throw FormatError("X/Y sequence: the argument size tables are not X's 186 and Omega Ruby's 213");
    Bytes out(x.begin(), x.begin() + 0x10);
    size_t p = 0x10;
    while (true)
    {
        if (p + 4 > x.size()) throw FormatError("X/Y sequence: no end mark");
        if (U32(x, p) == 0xFFFFFFFF)
        {
            if (p + 4 != x.size()) throw FormatError("X/Y sequence: bytes after the end mark");
            break;
        }
        if (p + 14 > x.size()) throw FormatError("X/Y sequence: a record cut short");
        const uint16_t command = (uint16_t)(x[p + 12] | x[p + 13] << 8), mine = XySequenceCommand(command);
        const uint32_t size = U32(xSizes, 4 * command), want = U32(orasSizes, 4 * mine);
        if (p + 14 + size > x.size()) throw FormatError("X/Y sequence: command " + std::to_string(command) + "'s arguments cut short (a variable size?)");
        if (want < size) throw FormatError("X/Y sequence: Omega Ruby's command " + std::to_string(mine) + " takes fewer bytes than X's " + std::to_string(command));
        Bytes arguments(x.begin() + (long)p + 14, x.begin() + (long)(p + 14 + size));
        arguments.resize(want, 0);
        if (record) record(mine, arguments);
        out.insert(out.end(), x.begin() + (long)p, x.begin() + (long)p + 12);
        out.push_back((uint8_t)mine);
        out.push_back((uint8_t)(mine >> 8));
        out.insert(out.end(), arguments.begin(), arguments.end());
        p += 14 + size;
    }
    for (int k = 0; k < 4; k++) out.push_back(0xFF);
    return out;
}

